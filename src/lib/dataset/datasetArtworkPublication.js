import { randomUUID } from "node:crypto";
import {
  copyFile,
  lstat,
  mkdir,
  open,
  readFile,
  readdir,
  rename,
  rm,
} from "node:fs/promises";
import { constants as fsConstants } from "node:fs";
import path from "node:path";
import {
  inspectLocalArtworkBytes,
  localArtworkFilename,
} from "../external/localArtworkAssets.js";

const DATASET_ARTWORK_FILENAME = /^[1-9][0-9]*\.[0-9a-f]{12}\.jpg$/;

async function requireRegularFile(filePath, label) {
  const info = await lstat(filePath);
  if (info.isSymbolicLink() || !info.isFile()) {
    throw new Error(`${label} must be a regular file inside the dataset artwork directory.`);
  }
  return info;
}

export async function assertDatasetArtworkDirectory(assetDirectory) {
  const info = await lstat(assetDirectory);
  if (info.isSymbolicLink() || !info.isDirectory()) {
    throw new Error("The dataset artwork directory must be a real directory, not a reparse point.");
  }
  return path.resolve(assetDirectory);
}

function resolveDatasetArtworkPath(assetDirectory, filename) {
  if (!DATASET_ARTWORK_FILENAME.test(filename)) {
    throw new Error(`Dataset artwork filename is invalid: ${filename}`);
  }
  const root = path.resolve(assetDirectory);
  const resolved = path.resolve(root, filename);
  if (!resolved.startsWith(`${root}${path.sep}`)) {
    throw new Error("Dataset artwork path escapes the dataset artwork directory.");
  }
  return resolved;
}

function resolveContainedPath(assetDirectory, filename) {
  const root = path.resolve(assetDirectory);
  const resolved = path.resolve(root, filename);
  if (!resolved.startsWith(`${root}${path.sep}`)) {
    throw new Error("Dataset artwork path escapes the dataset artwork directory.");
  }
  return resolved;
}

export function renderDatasetArtworkManifest(entries, sourceManifestSha256) {
  return `// Generated by scripts/download-amazon-artwork.mjs. Do not edit by hand.\n`
    + `export const DATASET_LOCAL_ARTWORK_SCHEMA_VERSION = 1;\n`
    + `export const DATASET_LOCAL_ARTWORK_SOURCE_MANIFEST_SHA256 = ${JSON.stringify(sourceManifestSha256)};\n\n`
    + `export const datasetLocalArtworkManifest = Object.freeze(${JSON.stringify(entries, null, 2)}.map((entry) => Object.freeze(entry)));\n`;
}

export async function verifyDatasetArtworkPublication({
  entries,
  accepted,
  sourceManifestSha256,
  assetDirectory,
  exactDirectory = true,
  requireSourceManifestDigest = true,
}) {
  await assertDatasetArtworkDirectory(assetDirectory);
  if (entries.length !== accepted.length) throw new Error("Dataset local artwork coverage is incomplete.");
  const acceptedById = new Map(accepted.map((entry) => [entry.publicId, entry]));
  if (acceptedById.size !== accepted.length) throw new Error("Accepted dataset artwork contains duplicate IDs.");
  const ids = new Set();
  const files = new Set();
  let totalBytes = 0;
  for (const entry of entries) {
    const source = acceptedById.get(entry.publicId);
    if (!source || ids.has(entry.publicId) || files.has(entry.filename)) {
      throw new Error("Dataset local artwork contains an unknown or duplicate entry.");
    }
    ids.add(entry.publicId);
    files.add(entry.filename);
    if (
      entry.sourceUrl !== source.artwork.thumbnailUrl
      || entry.sourcePageUrl !== source.artwork.sourceUrl
      || entry.musicBrainzReleaseId !== source.musicBrainzReleaseId
      || entry.musicBrainzReleaseGroupId !== source.musicBrainzReleaseGroupId
      || (requireSourceManifestDigest && entry.sourceManifestSha256 !== sourceManifestSha256)
    ) throw new Error(`Dataset local artwork provenance is stale for ${entry.publicId}.`);
    const filePath = resolveDatasetArtworkPath(assetDirectory, entry.filename);
    await requireRegularFile(filePath, `Dataset artwork ${entry.publicId}`);
    const body = await readFile(filePath);
    const inspected = inspectLocalArtworkBytes(body, { contentType: entry.contentType });
    for (const field of ["contentType", "byteLength", "width", "height", "sha256"]) {
      if (entry[field] !== inspected[field]) {
        throw new Error(`Dataset local artwork ${field} is invalid for ${entry.publicId}.`);
      }
    }
    if (entry.filename !== localArtworkFilename(entry.publicId, entry.sha256)) {
      throw new Error(`Dataset local artwork filename is invalid for ${entry.publicId}.`);
    }
    totalBytes += entry.byteLength;
  }
  if (exactDirectory) {
    let actualFiles = [];
    try {
      actualFiles = (await readdir(assetDirectory, { withFileTypes: true }))
        .filter((item) => item.name.toLowerCase().endsWith(".jpg"))
        .map((item) => item.name);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actualFiles.length !== files.size || actualFiles.some((file) => !files.has(file))) {
      throw new Error("Dataset artwork directory contains missing or orphan JPEG files.");
    }
  }
  return { count: entries.length, totalBytes };
}

export async function writeTextAtomically(filePath, content, {
  beforeRename = async () => {},
} = {}) {
  await mkdir(path.dirname(filePath), { recursive: true });
  const temporaryPath = path.join(path.dirname(filePath), `.${path.basename(filePath)}.${randomUUID()}.tmp`);
  let handle;
  try {
    handle = await open(temporaryPath, "wx");
    await handle.writeFile(content, "utf8");
    await handle.sync();
    await handle.close();
    handle = null;
    await beforeRename();
    await rename(temporaryPath, filePath);
  } finally {
    await handle?.close().catch(() => {});
    await rm(temporaryPath, { force: true }).catch(() => {});
  }
}

export async function publishContentAddressedDatasetArtwork(stagedPath, destinationPath, {
  expectedSha256,
  contentType = "image/jpeg",
}) {
  try {
    await requireRegularFile(destinationPath, "Published dataset artwork");
    const existing = inspectLocalArtworkBytes(await readFile(destinationPath), { contentType });
    if (existing.sha256 !== expectedSha256) {
      throw new Error(`Existing dataset artwork conflicts with its content-addressed filename: ${path.basename(destinationPath)}`);
    }
    await rm(stagedPath, { force: true });
    return "reused";
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  try {
    await copyFile(stagedPath, destinationPath, fsConstants.COPYFILE_EXCL);
    await rm(stagedPath, { force: true });
    return "published";
  } catch (error) {
    if (error.code !== "EEXIST") throw error;
    await requireRegularFile(destinationPath, "Published dataset artwork");
    const existing = inspectLocalArtworkBytes(await readFile(destinationPath), { contentType });
    if (existing.sha256 !== expectedSha256) throw error;
    await rm(stagedPath, { force: true });
    return "reused";
  }
}

export async function cleanupStaleDatasetArtwork(assetDirectory, expectedFiles) {
  await assertDatasetArtworkDirectory(assetDirectory);
  const removed = [];
  for (const item of await readdir(assetDirectory, { withFileTypes: true })) {
    if (expectedFiles.has(item.name) || !item.name.toLowerCase().endsWith(".jpg")) continue;
    const itemPath = resolveContainedPath(assetDirectory, item.name);
    await requireRegularFile(itemPath, "Stale dataset artwork");
    await rm(itemPath);
    removed.push(item.name);
  }
  return removed;
}

export async function publishDatasetArtworkManifest({
  entries,
  accepted,
  sourceManifestSha256,
  assetDirectory,
  manifestPath,
  afterManifestSwap = async () => {},
}) {
  await verifyDatasetArtworkPublication({
    entries,
    accepted,
    sourceManifestSha256,
    assetDirectory,
    exactDirectory: false,
  });
  await writeTextAtomically(
    manifestPath,
    renderDatasetArtworkManifest(entries, sourceManifestSha256),
  );
  await afterManifestSwap();
  const expectedFiles = new Set(entries.map((entry) => entry.filename));
  const removed = await cleanupStaleDatasetArtwork(assetDirectory, expectedFiles);
  const result = await verifyDatasetArtworkPublication({
    entries,
    accepted,
    sourceManifestSha256,
    assetDirectory,
    exactDirectory: true,
  });
  return { ...result, removed };
}
