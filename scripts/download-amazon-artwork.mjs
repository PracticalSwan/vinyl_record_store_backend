import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, readdir, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { AMAZON_DATASET_KEY } from "../src/lib/dataset/amazonReviews2023.js";
import {
  downloadLocalArtworkAsset,
  inspectLocalArtworkBytes,
  localArtworkFilename,
} from "../src/lib/external/localArtworkAssets.js";

const checkOnly = process.argv.includes("--check");
const dataRoot = path.join(process.cwd(), "data", "amazon-reviews-2023");
const enrichmentPath = path.join(dataRoot, "artwork-enrichment-v2.json");
const assetDirectory = path.join(process.cwd(), "public", "artwork", "dataset");
const generatedManifest = path.join(process.cwd(), "src", "data", "datasetLocalArtworkManifest.js");
const cacheRoot = path.join(process.cwd(), ".cache");
const configuredConcurrency = Number.parseInt(process.env.DATASET_ARTWORK_CONCURRENCY || "2", 10);
const downloadConcurrency = Number.isInteger(configuredConcurrency)
  ? Math.min(6, Math.max(1, configuredConcurrency))
  : 2;
const DOWNLOAD_RETRIES = 2;

function renderManifest(entries, sourceManifestSha256) {
  return `// Generated by scripts/download-amazon-artwork.mjs. Do not edit by hand.\n`
    + `export const DATASET_LOCAL_ARTWORK_SCHEMA_VERSION = 1;\n`
    + `export const DATASET_LOCAL_ARTWORK_SOURCE_MANIFEST_SHA256 = ${JSON.stringify(sourceManifestSha256)};\n\n`
    + `export const datasetLocalArtworkManifest = Object.freeze(${JSON.stringify(entries, null, 2)}.map((entry) => Object.freeze(entry)));\n`;
}

async function fileExists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function loadPublishedManifest() {
  try {
    const loadedModule = await import(`${pathToFileURL(generatedManifest).href}?v=${Date.now()}`);
    return Array.isArray(loadedModule.datasetLocalArtworkManifest)
      ? loadedModule.datasetLocalArtworkManifest
      : [];
  } catch {
    return [];
  }
}

async function verify(entries, accepted, sourceManifestSha256) {
  if (entries.length !== accepted.length) throw new Error("Dataset local artwork coverage is incomplete.");
  const acceptedById = new Map(accepted.map((entry) => [entry.publicId, entry]));
  const ids = new Set();
  const files = new Set();
  let totalBytes = 0;
  for (const entry of entries) {
    const source = acceptedById.get(entry.publicId);
    if (!source || ids.has(entry.publicId) || files.has(entry.filename)) {
      throw new Error("Dataset local artwork contains an unknown or duplicate entry.");
    }
    ids.add(entry.publicId);
    files.add(entry.filename);
    if (
      entry.sourceUrl !== source.artwork.thumbnailUrl
      || entry.sourcePageUrl !== source.artwork.sourceUrl
      || entry.musicBrainzReleaseId !== source.musicBrainzReleaseId
      || entry.musicBrainzReleaseGroupId !== source.musicBrainzReleaseGroupId
      || entry.sourceManifestSha256 !== sourceManifestSha256
    ) throw new Error(`Dataset local artwork provenance is stale for ${entry.publicId}.`);
    const body = await readFile(path.join(assetDirectory, entry.filename));
    const inspected = inspectLocalArtworkBytes(body, { contentType: entry.contentType });
    for (const field of ["contentType", "byteLength", "width", "height", "sha256"]) {
      if (entry[field] !== inspected[field]) throw new Error(`Dataset local artwork ${field} is invalid for ${entry.publicId}.`);
    }
    if (entry.filename !== localArtworkFilename(entry.publicId, entry.sha256)) {
      throw new Error(`Dataset local artwork filename is invalid for ${entry.publicId}.`);
    }
    totalBytes += entry.byteLength;
  }
  let actualFiles = [];
  try {
    actualFiles = (await readdir(assetDirectory, { withFileTypes: true }))
      .filter((item) => item.isFile() && item.name.endsWith(".jpg"))
      .map((item) => item.name);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (actualFiles.length !== files.size || actualFiles.some((file) => !files.has(file))) {
    throw new Error("Dataset artwork directory contains missing or orphan JPEG files.");
  }
  return { count: entries.length, totalBytes };
}

async function runWorkers(items, worker, concurrency = 6) {
  const output = new Array(items.length);
  let cursor = 0;
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      output[index] = await worker(items[index], index);
    }
  }));
  return output;
}

function isTransientDownloadError(error) {
  return [
    "LOCAL_ARTWORK_UPSTREAM_ERROR",
    "LOCAL_ARTWORK_UNREACHABLE",
    "LOCAL_ARTWORK_TIMEOUT",
  ].includes(error?.code);
}

async function downloadWithRetry(sourceUrl) {
  for (let attempt = 0; ; attempt += 1) {
    try {
      return await downloadLocalArtworkAsset(sourceUrl);
    } catch (error) {
      if (!isTransientDownloadError(error) || attempt >= DOWNLOAD_RETRIES) throw error;
      await new Promise((resolve) => setTimeout(resolve, 500 * (attempt + 1)));
    }
  }
}

const enrichment = JSON.parse(await readFile(enrichmentPath, "utf8"));
if (enrichment.datasetKey !== AMAZON_DATASET_KEY || enrichment.entriesDigest !== createHash("sha256").update(JSON.stringify(enrichment.entries)).digest("hex")) {
  throw new Error("The dataset artwork enrichment manifest is invalid.");
}
const accepted = enrichment.entries
  .filter((entry) => entry.status === "accepted")
  .sort((left, right) => left.publicId - right.publicId);
const sourceManifestSha256 = enrichment.entriesDigest;
const published = await loadPublishedManifest();

if (checkOnly) {
  const result = await verify(published, accepted, sourceManifestSha256);
  console.log(JSON.stringify({ status: "ok", ...result, sourceManifestSha256 }, null, 2));
  process.exit(0);
}

await mkdir(cacheRoot, { recursive: true });
await mkdir(assetDirectory, { recursive: true });
const stagingDirectory = await mkdtemp(path.join(cacheRoot, "dataset-artwork-download-"));
const publishedById = new Map(published.map((entry) => [entry.publicId, entry]));
let reused = 0;
let downloaded = 0;
try {
  const entries = await runWorkers(accepted, async (source, index) => {
    const previous = publishedById.get(source.publicId);
    if (
      previous
      && previous.sourceUrl === source.artwork.thumbnailUrl
      && previous.sourceManifestSha256 === sourceManifestSha256
      && await fileExists(path.join(assetDirectory, previous.filename))
    ) {
      reused += 1;
      return previous;
    }
    const asset = await downloadWithRetry(source.artwork.thumbnailUrl);
    const filename = localArtworkFilename(source.publicId, asset.sha256);
    await writeFile(path.join(stagingDirectory, filename), asset.body);
    downloaded += 1;
    if ((index + 1) % 25 === 0 || index === accepted.length - 1) {
      process.stderr.write(`[Dataset artwork ${index + 1}/${accepted.length}] ${source.publicId}\n`);
    }
    return {
      publicId: source.publicId,
      filename,
      assetPath: `/artwork/dataset/${filename}`,
      sourceUrl: source.artwork.thumbnailUrl,
      finalUrl: asset.finalUrl,
      sourcePageUrl: source.artwork.sourceUrl,
      musicBrainzReleaseId: source.musicBrainzReleaseId,
      musicBrainzReleaseGroupId: source.musicBrainzReleaseGroupId,
      contentType: asset.contentType,
      byteLength: asset.byteLength,
      width: asset.width,
      height: asset.height,
      sha256: asset.sha256,
      retrievedAt: asset.retrievedAt,
      sourceManifestSha256,
    };
  }, downloadConcurrency);

  for (const entry of entries) {
    const staged = path.join(stagingDirectory, entry.filename);
    if (await fileExists(staged)) {
      const destinationPath = path.join(assetDirectory, entry.filename);
      if (await fileExists(destinationPath)) {
        const existing = inspectLocalArtworkBytes(await readFile(destinationPath), {
          contentType: entry.contentType,
        });
        if (existing.sha256 !== entry.sha256) {
          throw new Error(`Existing dataset artwork does not match its content-addressed filename: ${entry.filename}`);
        }
      } else {
        await rename(staged, destinationPath);
      }
    }
  }
  const expectedFiles = new Set(entries.map((entry) => entry.filename));
  for (const item of await readdir(assetDirectory, { withFileTypes: true })) {
    if (item.isFile() && item.name.endsWith(".jpg") && !expectedFiles.has(item.name)) {
      throw new Error(`Refusing to publish while orphan dataset artwork exists: ${item.name}`);
    }
  }
  await writeFile(generatedManifest, renderManifest(entries, sourceManifestSha256), "utf8");
  const result = await verify(entries, accepted, sourceManifestSha256);
  console.log(JSON.stringify({
    status: "ok",
    ...result,
    reused,
    downloaded,
    sourceManifestSha256,
  }, null, 2));
} finally {
  const resolved = path.resolve(stagingDirectory);
  if (!resolved.startsWith(`${path.resolve(cacheRoot)}${path.sep}`)) {
    throw new Error("Refusing to remove an artwork staging path outside the cache root.");
  }
  await rm(resolved, { recursive: true, force: true });
}
